def object_rows(ax, names, gap_rows=True, labels=True):
    """Object rows with a half-row gap between cohorts; returns y positions."""
    def cohort(n):
        return 'NSCLC' if n in LUNG else 'BCC' if n in BCC else 'Other'
    y, pos, previous = [], 0., None
    for n in names:
        if gap_rows and previous is not None and cohort(n) != cohort(previous):
            pos += .6
        y.append(pos)
        pos += 1
        previous = n
    ax.set_yticks(y, [SHORT[n] for n in names] if labels else [])
    ax.set_ylim(pos - .4, -.6)
    ax.tick_params(axis='y', length=0)
    return np.array(y)


