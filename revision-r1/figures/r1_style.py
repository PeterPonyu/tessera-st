class Canvas:
    """A fixed-size figure whose children are placed in points from the upper-left corner."""

    def __init__(self, height, width=W):
        self.W, self.H = float(width), float(height)
        self.fig = plt.figure(figsize=(self.W / 72, self.H / 72))
        self.fig._r1_layout = {'canvas_points': [self.W, self.H], 'placement': 'explicit points from upper-left'}
        self.letters = []

    def rect(self, x, y, w, h):
        return [x / self.W, 1 - (y + h) / self.H, w / self.W, h / self.H]

    def fx(self, x):
        return x / self.W

    def fy(self, y):
        return 1 - y / self.H

    def text_width(self, strings, size, weight='normal'):
        self.fig.canvas.draw()
        renderer = self.fig.canvas.get_renderer()
        prop = FontProperties(family=FAMILY, size=size, weight=weight)
        widths = [renderer.get_text_width_height_descent(str(s), prop, ismath=False)[0] * 72 / self.fig.dpi
                  for s in strings if str(s)]
        return max(widths) if widths else 0.0

    def axes(self, x, y, w, h, **kwargs):
        assert w > 0 and h > 0, (x, y, w, h)
        return self.fig.add_axes(self.rect(x, y, w, h), **kwargs)

    def map_axes(self, x, y, w, h, xlim, ylim, halign='left', valign='top', invert_y=True):
        """Equal-aspect axes sized to the data and fitted inside the box; returns (ax, box)."""
        dx, dy = abs(xlim[1] - xlim[0]), abs(ylim[1] - ylim[0])
        ratio = dy / dx
        mw, mh = (w, w * ratio) if w * ratio <= h else (h / ratio, h)
        mx = x + {'left': 0, 'center': (w - mw) / 2, 'right': w - mw}[halign]
        my = y + {'top': 0, 'center': (h - mh) / 2, 'bottom': h - mh}[valign]
        ax = self.axes(mx, my, mw, mh)
        ax.set_xlim(*xlim)
        ax.set_ylim(*(ylim[::-1] if invert_y else ylim))
        ax.set_aspect('equal', adjustable='box')
        ax.set_xticks([])
        ax.set_yticks([])
        for spine in ax.spines.values():
            spine.set_visible(False)
        return ax, (mx, my, mw, mh)

    def text(self, x, y, s, size=NOTE, ha='left', va='baseline', gid=None, **kwargs):
        artist = self.fig.text(self.fx(x), self.fy(y), s, fontsize=size, ha=ha, va=va, color=INK,
                               fontweight='normal', **kwargs)
        if gid:
            artist.set_gid(gid)
        return artist

    def letter(self, x, y, letter):
        """Bold lowercase panel letter; (x, y) is its left edge and baseline."""
        artist = self.fig.text(self.fx(x), self.fy(y), letter, fontsize=LETTER, fontweight='bold', color=INK,
                               ha='left', va='baseline')
        artist.set_gid('panel-label')
        self.letters.append(letter)
        return artist

    def header(self, x, y, letter, title, title_size=TITLE):
        """Letter at the block's left edge, short title on the same baseline just to its right."""
        if letter:
            self.letter(x, y + BASELINE, letter)
        artist = self.text(x + (TITLE_OFFSET if letter else 0), y + BASELINE, title, size=title_size)
        artist.set_gid('panel-title')
        return artist

    def panel(self, x, y, w, h, letter, title, left, bottom, right=4.0, top=HEADER):
        """Header plus a plotting area inset by explicit tick/label allowances (points)."""
        self.header(x, y, letter, title)
        return self.axes(x + left, y + top, w - left - right, h - top - bottom)

    def row_letter(self, x, y, letter, title, y_center):
        """Map-grid convention: bold letter at the lane top, rotated row title centred below it."""
        self.letter(x, y, letter)
        artist = self.text(x + 5, y_center, title, size=CELL, ha='center', va='center', rotation=90)
        artist.set_gid('panel-title')
        return artist

    def legend(self, handles, x, y, ncol, size=LEGEND, **kwargs):
        """Legend whose upper centre is at (x, y) canvas points."""
        options = dict(frameon=False, columnspacing=1.0, handletextpad=.35, borderaxespad=0, borderpad=0,
                       fontsize=size)
        options.update(kwargs)
        return self.fig.legend(handles=handles, loc='upper center', ncol=ncol,
                               bbox_to_anchor=(self.fx(x), self.fy(y)), bbox_transform=self.fig.transFigure,
                               **options)

    def fitted_legend(self, handles, x, y, max_width, size=LEGEND, **kwargs):
        """Fewest rows whose rendered width fits max_width points."""
        n = len(handles)
        for rows in range(1, n + 1):
            ncol = int(np.ceil(n / rows))
            legend = self.legend(handles, x, y, ncol, size=size, **kwargs)
            self.fig.canvas.draw()
            width = legend.get_window_extent(self.fig.canvas.get_renderer()).width * 72 / self.fig.dpi
            if width <= max_width or ncol == 1:
                return legend
            legend.remove()
        return legend

    def extent(self, artist):
        """(x0, y0, x1, y1) in canvas points from the upper-left corner."""
        self.fig.canvas.draw()
        box = artist.get_window_extent(self.fig.canvas.get_renderer())
        s = 72 / self.fig.dpi
        return box.x0 * s, self.H - box.y1 * s, box.x1 * s, self.H - box.y0 * s

    def resize(self, height):
        """Shrink a provisional canvas to its content while keeping every point position."""
        old, fig = self.H, self.fig
        boxes = [(ax, ax.get_position(original=True)) for ax in fig.axes]
        fig.set_size_inches(self.W / 72, height / 72, forward=False)
        for ax, b in boxes:
            top = (1 - b.y1) * old
            h = b.height * old
            ax.set_position([b.x0, 1 - (top + h) / height, b.width, h / height])
        for t in fig.texts:
            x, y = t.get_position()
            t.set_position((x, 1 - (1 - y) * old / height))
        for lg in fig.legends:
            bb = lg.get_bbox_to_anchor()
            x0, y0 = fig.transFigure.inverted().transform((bb.x0, bb.y0))
            lg.set_bbox_to_anchor((x0, 1 - (1 - y0) * old / height), transform=fig.transFigure)
        self.H = height
        fig._r1_layout['canvas_points'] = [self.W, height]


