def visible_texts(fig):
    texts = list(fig.texts)
    for legend in fig.legends:
        texts += legend.get_texts()
    for ax in fig.axes:
        texts += list(ax.texts) + [ax.xaxis.label, ax.yaxis.label, ax.title]
        for axis in (ax.xaxis, ax.yaxis):
            for tick in axis._update_ticks():
                texts += [label for label in (tick.label1, tick.label2) if label.get_visible()]
        if ax.get_legend() is not None:
            texts += ax.get_legend().get_texts()
    return [t for t in texts if t.get_visible() and t.get_text().strip()]


def _text_polygon(artist, box, renderer, s):
    """Corners (points) of a text run's own rotated rectangle; the axis-aligned box when exact."""
    x0, y0, x1, y1 = box.x0 * s, box.y0 * s, box.x1 * s, box.y1 * s
    angle = artist.get_rotation() % 180
    if angle in (0, 90) or '\n' in artist.get_text():
        return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]
    w, h, _ = renderer.get_text_width_height_descent(artist.get_text(), artist.get_fontproperties(), ismath=False)
    w, h = w * s, h * s
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2  # a rotated rectangle shares its centre with its bounding box
    t = np.radians(artist.get_rotation())
    u, v = np.array([np.cos(t), np.sin(t)]), np.array([-np.sin(t), np.cos(t)])
    return [tuple(np.array([cx, cy]) + a * w / 2 * u + b * h / 2 * v) for a, b in [(-1, -1), (1, -1), (1, 1), (-1, 1)]]


def _polygons_overlap(p, q, tolerance):
    """Separating-axis test for two convex quadrilaterals; overlap must exceed the tolerance."""
    for poly in (p, q):
        for i in range(4):
            edge = np.subtract(poly[(i + 1) % 4], poly[i])
            axis = np.array([-edge[1], edge[0]]) / (np.hypot(*edge) or 1)
            a = [float(np.dot(axis, c)) for c in p]
            b = [float(np.dot(axis, c)) for c in q]
            if min(max(a), max(b)) - max(min(a), min(b)) <= tolerance:
                return False
    return True


def check_text_layout(fig, name, tolerance=0.3):
    """Reject overlapping text runs (their own rotated rectangles) and text outside the canvas (points)."""
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    s = 72 / fig.dpi
    width, height = fig.bbox.width * s, fig.bbox.height * s
    boxes = []
    for artist in visible_texts(fig):
        box = artist.get_window_extent(renderer)
        if box.width == 0 or box.height == 0:
            continue
        x0, y0, x1, y1 = box.x0 * s, box.y0 * s, box.x1 * s, box.y1 * s
        if x0 < -tolerance or y0 < -tolerance or x1 > width + tolerance or y1 > height + tolerance:
            raise AssertionError(f'{name}: text leaves the canvas: {artist.get_text()!r} '
                                 f'({x0:.1f},{y0:.1f})-({x1:.1f},{y1:.1f}) on {width:.1f}x{height:.1f}')
        boxes.append((artist, _text_polygon(artist, box, renderer, s)))
    overlaps = []
    for (a, p), (b, q) in itertools.combinations(boxes, 2):
        if _polygons_overlap(p, q, tolerance):
            overlaps.append((a.get_text(), b.get_text()))
    if overlaps:
        raise AssertionError(f'{name}: overlapping text runs: {overlaps[:8]}')
    return {'text_runs_checked': len(boxes), 'overlapping_text_runs': 0, 'text_outside_canvas': 0,
            'canvas_points': [round(width, 2), round(height, 2)]}


def check_letter_clearance(fig, name, clearance=1.0):
    """Panel letters keep a clear margin from every axes frame and every other text run."""
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    s = 72 / fig.dpi
    letters = [t for t in fig.texts if t.get_gid() == 'panel-label']
    frames = [ax.get_window_extent(renderer) for ax in fig.axes if ax.axison]
    pad = clearance / s
    for t in letters:
        b = t.get_window_extent(renderer)
        for f in frames:
            w = min(b.x1 + pad, f.x1) - max(b.x0 - pad, f.x0)
            h = min(b.y1 + pad, f.y1) - max(b.y0 - pad, f.y0)
            if w > 0 and h > 0:
                raise AssertionError(f'{name}: panel letter {t.get_text()!r} is within {clearance} pt of an axes frame')
    return {'panel_letters': [t.get_text() for t in letters], 'letter_axes_clearance_points': clearance}


def save(cv, name, plot_data=None):
    """Audit typography and layout, then write the vector PDF (and a 150-dpi QA PNG)."""
    fig = cv.fig
    letters, sizes = [], []
    for artist in visible_texts(fig):
        text = artist.get_text()
        for pattern in BANNED:
            assert not re.search(pattern, text), (name, text, pattern)
        assert artist.get_fontfamily() == [FAMILY], (name, text, artist.get_fontfamily())
        weight = artist.get_fontweight()
        if artist.get_gid() == 'panel-label':
            assert weight == 'bold' and re.fullmatch('[a-z]', text), (name, text)
            letters.append(text)
        else:
            assert weight in ('normal', 400), (name, text, weight)
            sizes.append(artist.get_fontsize())
    assert sorted(letters) == [chr(97 + i) for i in range(len(letters))], (name, letters)
    assert min(sizes) >= NOTE - 1e-9, (name, min(sizes))
    layout = check_text_layout(fig, name)
    clearance = check_letter_clearance(fig, name)
    PDF_OUT.mkdir(parents=True, exist_ok=True)
    (QA_OUT / 'native').mkdir(parents=True, exist_ok=True)
    target = PDF_OUT / (name + '.pdf')
    fig.savefig(target, dpi=330, metadata={'CreationDate': None, 'ModDate': None, 'Creator': 'matplotlib',
                                              'Producer': 'matplotlib pdf backend'})
    fig.savefig(QA_OUT / 'native' / (name + '.png'), dpi=150)
    plt.close(fig)
    AUDIT[name] = {'letters': sorted(letters), 'min_text_points': min(sizes), 'max_text_points': max(sizes),
                   'letter_points': LETTER, **layout, **clearance, 'canvas_points': fig._r1_layout['canvas_points']}
    if plot_data is not None:
        PLOT_DATA[name] = plot_data
    return target


def finite(value):
    if isinstance(value, dict):
        return {str(k): finite(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [finite(v) for v in value]
    if isinstance(value, np.ndarray):
        return finite(value.tolist())
    if isinstance(value, (np.floating, float)):
        return None if not np.isfinite(value) else float(value)
    if isinstance(value, np.integer):
        return int(value)
    return value
